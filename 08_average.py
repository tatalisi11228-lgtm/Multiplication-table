# تمرین ۰۸ — میانگین N عدد
#
# صورت تمرین:
#   اول بپرس «چند عدد داری؟»، بعد همان تعداد عدد بگیر و میانگینشان را چاپ کن.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   How many numbers? 4
#   Number 1: 10
#   Number 2: 20
#   Number 3: 30
#   Number 4: 40
#   Average: 25.0
#
# ---------------------------------------------------------------
# ابزار جدید: جمع‌کننده (accumulator)
# ---------------------------------------------------------------
#
#   تا حالا داخل حلقه فقط چاپ می‌کردیم. حالا می‌خواهیم داخل حلقه یک
#   مقدار را **جمع** کنیم و بعد از تمام‌شدن حلقه از آن استفاده کنیم.
#
#   الگو این است: یک جعبه را قبل از حلقه خالی می‌کنی، و هر دور چیزی
#   به آن اضافه می‌کنی.
#
#       total = 0                    ← قبل از حلقه: جعبهٔ خالی
#       for i in range(1, 4):
#           total = total + i        ← هر دور: اضافه کن
#       print(total)                 ← بعد از حلقه: 6
#
#   مسیر جعبه را دنبال کن:
#       اول:            total = 0
#       دور ۱ (i=1):    total = 0 + 1 = 1
#       دور ۲ (i=2):    total = 1 + 2 = 3
#       دور ۳ (i=3):    total = 3 + 3 = 6
#
#   دو نکتهٔ کلیدی:
#
#   ۱. خط total = 0 باید **بیرون و قبل** از حلقه باشد. اگر داخل حلقه
#      باشد، هر دور جعبه را خالی می‌کند و هیچ‌چیز جمع نمی‌شود.
#
#   ۲. total = total + i عجیب به نظر می‌رسد ولی درست است:
#      «مقدار جدید جعبه = مقدار قدیمی جعبه + چیزِ تازه». این خط در هر
#      دور اجرا می‌شود و جعبه را به‌روز می‌کند.
#
#   در این تمرین، «چیزِ تازه» عددی است که کاربر وارد می‌کند — پس آن
#   input() هم باید **داخل** حلقه باشد، وگرنه فقط یک بار پرسیده می‌شود.
#
#   میانگین هم همان تقسیم آشناست: جمع ÷ تعداد.
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. اگر total = 0 را داخل حلقه بگذاری چه می‌شود؟ حدس بزن، بعد
#      امتحان کن. (این هم یک باگ خاموش است: خطا نمی‌دهد، جواب غلط می‌دهد.)
#
#   ۲. اگر کاربر بگوید ۴ عدد دارد، باید از «Number 1» تا «Number 4» را
#      بپرسیم. پس range تا کجا باشد؟ چرا range(1, n + 1) و نه
#      range(1, n)؟ (همان تلهٔ تمرین ۰۷.) و اگر فقط range(n) بنویسی،
#      از چه عددی شروع می‌شود؟
#
#   ۳. اگر کاربر برای «چند عدد؟» صفر وارد کند، چه اتفاقی می‌افتد؟
#      اسم آن خطا را در تمرین ۰۳ دیده‌ای.
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. بزرگ‌ترین و کوچک‌ترین عددی که کاربر داده را هم چاپ کن
#      (راهنما: دو جعبهٔ دیگر، با همان الگوی جمع — و مقایسه‌ای که
#       در تمرین ۰۶ یاد گرفتی).
#   ۲. اگر تعداد اعداد صفر بود، به‌جای خطا پیام بده.

# کد خودت را از این‌جا بنویس
n = int(input("How many numbers? "))

if n == 0:
    print("No numbers to average.")
else:
    total = 0
    for i in range(1, n + 1):
        x = float(input(f"Number {i}: "))
        total = total + x
        if i == 1:
            largest = x
            smallest = x
        else:
            if x > largest:
                largest = x
            if x < smallest:
                smallest = x
    average = total / n
    print(f"average: {round(average, 2)}\n"
          f"Largest: {round(largest, 2)}\n"
          f"Smallest: {round(smallest, 2)}"
        )

