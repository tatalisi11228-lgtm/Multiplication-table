# تمرین ۰۳ — تقسیم صورت‌حساب
#
# صورت تمرین:
#   از کاربر سه چیز بپرس:
#     ۱. مبلغ کل صورت‌حساب
#     ۲. درصد انعام (tip)
#     ۳. تعداد نفرات
#   بعد حساب کن هر نفر چقدر باید بدهد.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Bill amount: 100
#   Tip percent: 15
#   Number of people: 4
#
#   Bill:             100.0
#   Tip (15.0%):       15.0
#   Total:            115.0
#   Each person pays:  28.75
#
# ابزارهایی که لازم داری:
#   input(...)      گرفتن ورودی — یادت باشد: همیشه «رشته» برمی‌گرداند
#   float(...)      تبدیل رشته به عدد اعشاری   ← اینجا لازم داری!
#   int(...)        تبدیل رشته به عدد صحیح     ← برای تعداد نفرات
#   round(عدد, n)   گرد کردن عدد تا n رقم اعشار
#   print(f"...")   چاپ کردن با f-string
#
# فرمول‌ها:
#   انعام       = مبلغ × درصد ÷ ۱۰۰
#   مبلغ کل     = مبلغ + انعام
#   سهم هر نفر  = مبلغ کل ÷ تعداد نفرات
#
# سه سؤال برای فکر کردن:
#   ۱. چرا برای «تعداد نفرات» بهتر است int() بزنی و نه float()؟
#   ۲. اگر تعداد نفرات را ۰ وارد کنی، چه اتفاقی می‌افتد؟ امتحان کن —
#      خطایی می‌گیری که اسمش را قبلاً شنیده‌ای ولی این یکی فرق دارد.
#   ۳. اگر کاربر جای عدد، حرف بنویسد (مثلاً "abc") چه می‌شود؟
#
# چالش اضافه (اختیاری):
#   خروجی را با round(..., 2) گرد کن تا فقط دو رقم اعشار نشان دهد.

# کد خودت را از این‌جا بنویس
bill = float(input("Bill amount:"))
tip_percent = float(input("Tip percent:"))
people = int(input("Number of people:"))

tip_amount = bill * tip_percent / 100
total = bill + tip_amount
each = total / people

print(f"Bill: {round(bill, 2)}")
print(f"Each person pays: {round(each, 2)}")
print(f"Tip ({tip_percent}%):   {round(tip_amount, 2)}")
print(f"Total:    {round(total, 2)}")
