#
#   ۲. می‌شود پالیندروم را **بدون** ساختن رشتهٔ برعکس تشخیص داد؟
#      (راهنما: کاراکتر اول را با آخرین مقایسه کن، بعد دومی را با
#      یکی‌مانده‌به‌آخر … تا وسط. اسم این روش «دو اشاره‌گر» است.)
#      کدام راه سریع‌تر است؟ کدام خواناتر؟
#
