# تمرین ۱۱ — آیا کلمه پالیندروم است؟
#
# صورت تمرین:
#   یک کلمه از کاربر بگیر و بگو آیا پالیندروم است یا نه.
#   (پالیندروم = کلمه‌ای که از هر دو طرف یکسان خوانده می‌شود: level، radar، civic)
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter a word: level
#   level is a palindrome
#
#   Enter a word: hello
#   hello is not a palindrome
#
# ---------------------------------------------------------------
# ایدهٔ تمرین
# ---------------------------------------------------------------
#
#   در تمرین ۱۰ یاد گرفتی چطور یک رشته را برعکس کنی. حالا فقط باید
#   آن را با خودِ رشته **مقایسه** کنی:
#
#       اگر رشته == برعکسش   →  پالیندروم است
#       وگرنه                →  نیست
#
#   مقایسهٔ دو رشته با `==` انجام می‌شود — مثل مقایسهٔ دو عدد. پایتون
#   کاراکتربه‌کاراکتر چک می‌کند و اگر همه یکی بودند True می‌دهد.
#
#       "level" == "level"   →  True
#       "level" == "Level"   →  False   ← حرف بزرگ و کوچک فرق دارند!
#
# ---------------------------------------------------------------
# ابزار جدید: بریدن رشته (slicing) — راه کوتاهِ برعکس‌کردن
# ---------------------------------------------------------------
#
#   حالا که خودت دستی رشته را برعکس کردی، نسخهٔ آمادهٔ پایتون را هم ببین:
#
#       word[::-1]      →  همان رشته، برعکس
#       "hello"[::-1]   →  'olleh'
#
#   این «بریدن» (slice) است و شکل کلی‌اش:
#
#       رشته[شروع : پایان : گام]
#
#   وقتی شروع و پایان را خالی بگذاری و گام را منفی (‎-1‎) بدهی، یعنی
#   «از آخر به اول، یکی‌یکی». چند مثال:
#
#       "python"[0:3]    →  'pyt'    (کاراکترهای ۰ تا ۲)
#       "python"[2:]     →  'thon'   (از ۲ تا آخر)
#       "python"[:4]     →  'pyth'   (از اول تا ۳)
#       "python"[::2]    →  'pto'    (یکی در میان)
#       "python"[::-1]   →  'nohtyp' (برعکس)
#
#   می‌توانی از این استفاده کنی یا از حلقهٔ تمرین ۱۰ — هر دو درست‌اند.
#   (بهتر است اول با حلقهٔ خودت بنویسی، بعد نسخهٔ کوتاه را هم امتحان کنی.)
#
# ---------------------------------------------------------------
# ابزار کوچک: lower() — همه را حروف کوچک کن
# ---------------------------------------------------------------
#
#       "Level".lower()   →  'level'
#       "LEVEL".lower()   →  'level'
#
#   برای پرسش ۱ به کارت می‌آید: آیا "Level" پالیندروم است؟
#   از نظر کامپیوتر، "Level" با "level" یکی نیست — ولی از نظر آدم، بله!
#
