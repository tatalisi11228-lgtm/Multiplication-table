#پالیندروم را **بدون** ساختن رشتهٔ برعکس تشخیص بده
word = input("Enter a word: ").lower()

left = 0
right = len(word) - 1
is_palindrome = True

if word == "":
    print("You didn't enter anything")
else:
    while left < right:
        if word[left] != word[right]:
            is_palindrome = False
            break
        left = left + 1
        right = right - 1

    if is_palindrome:
        print(f"{word} is a palindrome")
    else:
        print("It isn't a palindrome")
