# تمرین ۰۴ — تبدیل نمره به حرف
#
# صورت تمرین:
#   از کاربر یک نمرهٔ بین ۰ تا ۱۰۰ بگیر و بگو چه حرفی می‌گیرد.
#
#       نمره          حرف
#       ۹۰ تا ۱۰۰     A
#       ۸۰ تا ۸۹      B
#       ۷۰ تا ۷۹      C
#       ۶۰ تا ۶۹      D
#       زیر ۶۰        F
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter your score: 85
#   Your grade is B
#
# ---------------------------------------------------------------
# ابزار جدید: دستور شرطی (if / elif / else)
# ---------------------------------------------------------------
#
#   if شرط:
#       کاری که اگر شرط درست بود انجام بده
#   elif شرط دیگری:
#       کاری که اگر آن شرط درست بود
#   else:
#       کاری که اگر هیچ‌کدام درست نبود
#
# پایتون شرط‌ها را به ترتیب از بالا به پایین چک می‌کند و
# به محض اینکه یکی درست بود، بقیه را نادیده می‌گیرد.
#
# ---------------------------------------------------------------
# ⚠️ مهم‌ترین نکتهٔ این تمرین: فاصله‌گذاری (indentation)
# ---------------------------------------------------------------
#
# در پایتون، خط‌های داخل if باید با «فاصله» جلوتر باشند:
#
#   if score >= 90:
#       print("A")        ← ۴ فاصله جلوتر
#   print("تمام")         ← بدون فاصله، پس بیرون از if است
#
# این فاصله‌ها فقط برای زیبایی نیستند — پایتون از همین‌ها می‌فهمد
# کدام خط داخل شرط است و کدام بیرون. اگر اشتباه بزنی، خطا می‌گیری.
#
# (نگران نباش: VS Code بعد از تایپ if و اینتر، خودش فاصله را می‌گذارد.
#  فقط باید بدانی که نباید پاکش کنی!)
#
# ---------------------------------------------------------------
# عملگرهای مقایسه
# ---------------------------------------------------------------
#
#   >    بزرگ‌تر              <    کوچک‌تر
#   >=   بزرگ‌تر یا مساوی      <=   کوچک‌تر یا مساوی
#   ==   مساوی (دوتا مساوی!)   !=   نامساوی
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. چرا برای «مساوی» باید == بنویسیم و نه = ؟
#      (راهنما: = قبلاً چه کاری برایمان می‌کرد؟)
#
#   ۲. اگر کاربر نمرهٔ ۱۰۵ وارد کند، چه اتفاقی می‌افتد؟ آیا درست است؟
#
#   ۳. ترتیب شرط‌ها مهم است؟ اگر اول بنویسی if score >= 60 و بعد
#      elif score >= 90، برای نمرهٔ ۹۵ چه جوابی می‌گیری؟ چرا؟
#      این را حتماً امتحان کن — یکی از رایج‌ترین اشتباهات است.
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   برای هر حرف یک پیام تشویقی هم چاپ کن.
#   همچنین اگر نمره بیرون از بازهٔ ۰ تا ۱۰۰ بود، پیام خطا بده.

# کد خودت را از این‌جا بنویس
score = float(input("Enter your score: "))

if score < 0 or score > 100:
    print("Enter a number from zero to one hundred")
elif score >= 90:
    print("Your grade is A")
elif score >= 80:
    print("Your grade is B")
elif score >= 70:
    print("Your grade is C")
elif score >= 60:
    print("Your grade is D")
else:
    print("Your grade is F")


