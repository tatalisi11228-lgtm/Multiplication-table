# تمرین ۱۰ — معکوس کردن یک رشته
#
# صورت تمرین:
#   یک کلمه (یا جمله) از کاربر بگیر و آن را برعکس چاپ کن.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter a word: hello
#   olleh
#
#   Enter a word: python
#   nohtyp
#
# ---------------------------------------------------------------
# خوش آمدی به مرحلهٔ ۴: رشته‌ها (string)
# ---------------------------------------------------------------
#
#   تا حالا رشته را فقط چاپ می‌کردیم. حالا می‌خواهیم داخلش را ببینیم:
#   رشته یک **دنباله از کاراکترها** است، و پایتون اجازه می‌دهد هر
#   کاراکتر را جدا صدا بزنی.
#
# ---------------------------------------------------------------
# ابزار جدید ۱: ایندکس — شمارهٔ هر کاراکتر
# ---------------------------------------------------------------
#
#   شماره‌گذاری از **صفر** شروع می‌شود، نه یک:
#
#       word = "python"
#       word[0]  →  'p'        (اولین کاراکتر)
#       word[1]  →  'y'
#       word[5]  →  'n'        (آخرین کاراکتر — چون ۶ حرف است: ۰ تا ۵)
#
#   و شماره‌های منفی از **آخر** می‌شمارند:
#
#       word[-1] →  'n'        (آخرین)
#       word[-2] →  'o'
#
#   len(word)  →  6            (تعداد کاراکترها — از `len` قبلاً استفاده کردی)
#
#   و اگر شماره‌ای بدهی که وجود ندارد؟
#       word[10]  →  IndexError: string index out of range
#
# ---------------------------------------------------------------
# ابزار جدید ۲: حلقه روی خودِ رشته
# ---------------------------------------------------------------
#
#   با `for` می‌توانی مستقیم روی یک رشته بگردی — بدون range و بدون i:
#
#       for char in "abc":
#           print(char)
#
#   خروجی:  a  بعد  b  بعد  c
#
#   یعنی: «برای هر کاراکتری که در این رشته هست، این کار را بکن.»
#   اسم `char` دلخواه است (هر اسمی می‌توانی بگذاری).
#
# ---------------------------------------------------------------
# ابزار جدید ۳: جعبهٔ خالی برای متن
# ---------------------------------------------------------------
#
#   در تمرین ۰۸ جعبهٔ جمع را با ۰ خالی کردیم، چون ۰ در جمع بی‌اثر است.
#   برای متن، معادلِ ۰ یک **رشتهٔ خالی** است:  ""
#
#       result = ""                    ← جعبهٔ خالیِ متن
#       result = char + result         ← کاراکتر جدید را اضافه کن
#
#   اما یک تفاوت مهم با جمع: در جمع ترتیب مهم نبود، اینجا **هست**.
#   `char + result` یعنی کاراکتر جدید **جلوی** قبلی‌ها می‌چسبد — و
#   همین باعث می‌شود رشته برعکس شود. (سؤال ۲ همین را می‌پرسد.)
#
#   نمونهٔ مسیر جعبه برای "abc":
#       اول:        result = ""
#       'a':        result = "a" + ""    = "a"
#       'b':        result = "b" + "a"   = "ba"
#       'c':        result = "c" + "ba"  = "cba"     → برعکس شد!
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. چرا `result = ""` و نه `result = 0`؟ اگر ۰ بگذاری چه خطایی
#      می‌گیری؟ (اسمش را می‌دانی.)
#
#   ۲. اگر بنویسی `result = result + char` به‌جای `result = char + result`،
#      خروجی چه می‌شود؟ چرا؟ — این را حتماً امتحان کن؛ قلب این تمرین
#      همین یک جابه‌جایی است.
#
#   ۳. ایندکس صفر و منفی: `word[0]` و `word[-1]` برای "python" چه می‌دهند؟
#      آیا با `word[0]` می‌شود این تمرین را هم حل کرد؟ (راهنما: با
#      شمارشِ نزولی) کدام راه خواناتر است؟
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. به‌جای معکوس‌کردن کل جمله، فقط **هر کلمه** را معکوس کن و ترتیب
#      کلمات را نگه دار: "hello world" → "olleh dlrow"
#      (راهنما: `split()` و بعد دوباره چسباندن با " ".join — با هم
#       انجامش می‌دهیم اگر خواستی.)
#   ۲. تعداد حروف صدادار (a, e, i, o, u) را بشمار.
#   ۳. اگر کاربر خالی Enter بزند چه اتفاقی می‌افتد؟ امتحان کن.

# کد خودت را از این‌جا بنویس
word = input("Enter a word: ")

result = ""
for char in word:
       result = char + result

print(f"Its reverse is: {result}")

#چالش: برعکس کردن هر کلمه، با نگه داشتن ترتیب کلمه‌ها

sentence = input("Enter a name: ")
words = sentence.split()

parts = []
for word in words:
        rev = ""
        for char in word:
              rev = char + rev
        parts.append(rev)

print(" ".join(parts))

