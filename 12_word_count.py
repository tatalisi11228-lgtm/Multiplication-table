# تمرین ۱۲ — شمردن کلمه‌های یک جمله
#
# صورت تمرین:
#   یک جمله از کاربر بگیر و بگو چند کلمه دارد.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter a sentence: I am learning python
#   4 words
#
# ---------------------------------------------------------------
# ابزار اصلی: split() + len()
# ---------------------------------------------------------------
#
#   در چالش تمرین ۱۰ با split() آشنا شدی: جمله را از جاهای خالی
#   می‌شکند و یک **لیست** از کلمه‌ها می‌دهد.
#
#       "I am learning python".split()
#       →  ['I', 'am', 'learning', 'python']
#
#   و len() تعداد اعضای یک لیست را می‌دهد — همان‌طور که طول یک
#   رشته را می‌داد:
#
#       len(['I', 'am', 'learning', 'python'])  →  4
#
#   پس شمارش کلمه‌ها در ساده‌ترین شکلش فقط دو خط است. ولی هدف این
#   تمرین این است که **خودت هم** بتوانی بشماری…
#
# ---------------------------------------------------------------
# راه دوم: شمارش دستی با شمارنده
# ---------------------------------------------------------------
#
#   همان الگوی شمارنده از تمرین ۰۸ و ۰۹، این بار روی کلمه‌ها:
#
#       count = 0                  ← قبل از حلقه
#       for word in words:
#           count = count + 1      ← هر دور یکی اضافه کن
#
#   بعد از حلقه، count همان عددی است که len(words) می‌داد.
#   (برای همین می‌گویند len یک «میان‌بر» است — کاری را می‌کند که
#    با حلقه هم می‌شد.)
#
# ---------------------------------------------------------------
# ابزار جدید: split با جداکنندهٔ دلخواه
# ---------------------------------------------------------------
#
#   اگر داخل پرانتز split چیزی بگذاری، از روی **همان** می‌شکند:
#
#       "a,b,c".split(",")      →  ['a', 'b', 'c']
#       "one-two".split("-")    →  ['one', 'two']
#
#   و اگر خالی بگذاری (split())، از روی هر فاصله و چند فاصله‌ای —
#   حتی tab و newline.
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. اگر کاربر فقط چند تا فاصله بزند و Enter ("   ")، خروجی چه
#      می‌شود؟ اول حدس بزن، بعد امتحان کن. (راهنما: "   ".split()
#      چه چیزی می‌دهد؟)
#
#   ۲. جمله‌ای با فاصله‌های اضافی: "I  am   learning" (دو و سه فاصله).
#      برنامه‌ات چند کلمه می‌شمارد؟ چرا؟ این یکی از زیبایی‌های
#      split() است.
#
#   ۳. اگر بخواهی **حروف** را بشمری (بدون فاصله‌ها)، چه می‌کنی؟
#      دو راه داری: یکی با len(word) روی هر کلمه و جمع‌کردن، یکی
#      با حذف فاصله‌ها و len روی کل جمله. کدام درست‌تر است؟
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. بلندترین کلمهٔ جمله را پیدا و چاپ کن. (راهنما: الگوی بزرگ‌ترین
#      از تمرین ۰۸ — ولی این بار با len(word) مقایسه کن.)
#   ۲. تعداد حروف جمله (بدون فاصله) را هم چاپ کن.
#   ۳. میانگین طول کلمه‌ها را چاپ کن.

# کد خودت را از این‌جا بنویس
words = input("Enter your sentence: ").split()

#if len(words) == 1:
 #   print(f"> {len(words)} word")
#elif len(words) > 1:
 #   print(f"> {len(words)} words")
#else:
 #   print("> You didn't enter anything")

longest = ""
letters = 0
if len(words) == 0:
    print("> You didn't enter anything")
else:
    for word in words:
        if len(word) > len(longest):
            longest = word
        letters = letters + len(word)

    average = letters / len(words)
    print(f"> {longest} is the longest word\n"
          f"> letters: {letters}, average: {round(average, 2)}")
