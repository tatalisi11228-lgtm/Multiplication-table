# تمرین ۱۳ — بزرگ‌ترین عدد، بدون max()
#
# صورت تمرین:
#   چند عدد از کاربر بگیر، آن‌ها را در یک لیست نگه دار، و بعد بگو
#   کدام بزرگ‌ترین است — **بدون** استفاده از max().
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   How many numbers? 4
#   Number 1: 10
#   Number 2: 40
#   Number 3: 25
#   Number 4: 5
#   The largest is 40.0
#
# ---------------------------------------------------------------
# خوش آمدی به مرحلهٔ ۵: لیست‌ها
# ---------------------------------------------------------------
#
#   تا حالا هر عدد را در یک متغیر جدا نگه می‌داشتیم (a، b، c). ولی اگر
#   کاربر بگوید «۱۰۰ عدد دارم» چه؟ ۱۰۰ متغیر؟!
#
#   لیست = یک **ظرف** برای چند مقدار، با یک اسم.
#
# ---------------------------------------------------------------
# ابزار جدید ۱: ساختن لیست خالی و پر کردنش
# ---------------------------------------------------------------
#
#       numbers = []              ← لیست خالی (ظرف خالی)
#       numbers.append(10)        ← ۱۰ را به آخر لیست اضافه کن
#       numbers.append(40)
#       print(numbers)            →  [10, 40]
#       print(len(numbers))       →  2
#
#   در چالش تمرین ۱۰ و تمرین ۱۲ هم از append استفاده کردی — همان است.
#
#   الگوی کاملِ «خواندن n عدد در لیست»:
#
#       numbers = []
#       for i in range(1, n + 1):
#           x = float(input(f"Number {i}: "))
#           numbers.append(x)
#
#   بعد از حلقه، همهٔ عددها در numbers هستند و می‌توانی هر کاری با
#   آن‌ها بکنی — بدون اینکه دوباره از کاربر بپرسی.
#
# ---------------------------------------------------------------
# ابزار جدید ۲: ایندکس و گشتن روی لیست
# ---------------------------------------------------------------
#
#       numbers[0]     ← اولین عضو (مثل رشته، از صفر)
#       numbers[-1]    ← آخرین عضو
#       len(numbers)   ← تعداد اعضا
#
#   و حلقه روی اعضا:
#
#       for n in numbers:
#           print(n)
#
#   (دقیقاً مثل for char in word، فقط روی لیست اعداد.)
#
# ---------------------------------------------------------------
# ایدهٔ الگوریتم: قانونِ «قهرمانِ فعلی»
# ---------------------------------------------------------------
#
#   قهرمان را اولین عضو لیست بگذار، بعد بقیه را با او مقایسه کن.
#   هر کس از او بزرگ‌تر بود، قهرمان جدید است:
#
#       largest = numbers[0]        ← قهرمان اول
#       for n in numbers:
#           if n > largest:
#               largest = n         ← قهرمان عوض شد
#
#   چرا numbers[0] و نه 0؟ چون اگر همهٔ عددها منفی باشند، ۰ از همه
#   بزرگ‌تر می‌شد و جواب غلط می‌داد (همان درس چالش ۰۸).
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. می‌شود بزرگ‌ترین را در **همان حلقه‌ای** پیدا کرد که عددها را
#      می‌خوانی؟ (بله!) پس چرا اصلاً لیست نگه داریم؟ چه چیزی را
#      از دست می‌دهیم اگر لیست نداشته باشیم؟
#
#   ۲. اگر لیست خالی باشد، `largest = numbers[0]` چه می‌دهد؟ اسم آن
#      خطا را می‌دانی. پس چه نگهبانی لازم است؟
#
#   ۳. `max(numbers)` همان کار را در یک خط می‌کند! پس چرا این تمرین
#      می‌گوید بدون max؟ (پاسخ کوتاه: چون باید بدانی داخلش چه خبر است.
#      بعد از این تمرین، هر وقت max زدی، می‌دانی چه کار می‌کند.)
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. کوچک‌ترین را هم پیدا کن (min بدون min()).
#   ۲. مجموع و میانگین را هم چاپ کن (الگوی جمع‌کنندهٔ ۰۸ روی لیست).
#   ۳. تعداد اعداد مثبت و منفی را بشمار.
#   ۴. میانگین را فقط برای عددهای بزرگ‌تر از صفر حساب کن.

# کد خودت را از این‌جا بنویس
# تا وقتی ورودی معتبر نده، دوباره می‌پرسد
while True:
    answer = input("How many numbers? ")

    if answer == "" or not answer.isdigit():
        print("Please enter a whole number.")
        continue

    n = int(answer)

    if n == 0:
        print("The number must be greater than zero.")
        continue



    # خواندن عددها در یک لیست
    numbers = []
    for i in range(1, n + 1):
        x = float(input(f"Number {i}: "))
        numbers.append(x)

    # الگوریتم «قهرمان فعلی»: بزرگ‌ترین، بدون max()
    largest = numbers[0]
    for num in numbers:
        if num > largest:
            largest = num

    print(f"The largest is {largest}")
