# تمرین ۰۱ — تبدیل سلسیوس به فارنهایت
#
# صورت تمرین:
#   ۱. از کاربر یک دما به سلسیوس بگیر.
#   ۲. با این فرمول به فارنهایت تبدیلش کن:  F = C * 9 / 5 + 32
#   ۳. جواب را در یک جملهٔ خوانا چاپ کن.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter temperature in Celsius: 25
#   25.0 degrees Celsius is 77.0 degrees Fahrenheit
#
# ابزارهایی که لازم داری:
#   input("...")   از کاربر متن میگیرد و آن را به‌صورت «رشته» برمی‌گرداند
#   float(...)     آن متن را به عدد اعشاری تبدیل می‌کند
#   print(...)     چیزی را روی صفحه نمایش می‌دهد
#   f"..."         رشتهٔ قالبی: f"{name}" مقدار را داخل متن می‌گذارد
#
# به این فکر کن:
#   اگر input() به تو «متن» می‌دهد، اگر مستقیم روی آن حساب کنی چه می‌شود؟
#   یک بار امتحان کن و ببین — دیدن آن پیام خطا ارزشش را دارد.

# ---------- کد تمرین ----------

# خط ۱: سؤال می‌پرسیم و جواب کاربر را در متغیری می‌ریزیم.
#         input() همیشه یک «رشته» (متن) برمی‌گرداند.
celsius_text = input("Enter temperature in Celsius: ")

# خط ۲: آن متن را به عدد اعشاری تبدیل می‌کنیم.
#         بدون این خط، خط ۳ با خطای TypeError می‌شکند.
celsius = float(celsius_text)

# خط ۳: فرمول تبدیل را حساب می‌کنیم و نتیجه را در متغیر جدید می‌ریزیم.
fahrenheit = celsius * 9 / 5 + 32

# خط ۴: نتیجه را داخل یک جملهٔ خوانا چاپ می‌کنیم.
#         حرف f قبل از کوتیشن یعنی: هر چیزی بین {} را حساب کن و جایش بگذار.
print(f"{celsius} degrees Celsius is {fahrenheit} degrees Fahrenheit")
