# تمرین ۰۶ — بزرگ‌ترینِ سه عدد
#
# صورت تمرین:
#   سه عدد از کاربر بگیر و بگو کدام‌یک بزرگ‌ترین است.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   First number: 12
#   Second number: 45
#   Third number: 7
#   45 is the largest
#
# ---------------------------------------------------------------
# ابزار جدید: ترکیب شرط‌ها با and
# ---------------------------------------------------------------
#
#   «a از b بزرگ‌تر است و از c هم بزرگ‌تر» به زبان پایتون:
#
#       if a > b and a > c:
#
#   و برای عدد دوم، وقتی مطمئن شدیم اولی بزرگ‌ترین نیست:
#
#       elif b > c:
#
#   فقط سه حالت داری: a بزرگ‌ترین است، b بزرگ‌ترین است، یا c.
#   پس نردبانت سه پله دارد (و پلهٔ آخر همان نتیجه‌گیری از دو تای قبل است).
#
#   راه دوم، بدون and: شرط‌های تودرتو —
#       if a > b:
#           if a > c:
#               ...
#   هر دو راه درست‌اند؛ سؤال ۲ می‌پرسد کدام خواناتر است.
#
#   یادت باشد: هر سه ورودی عددند، پس هر سه را تبدیل کن.
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. اگر دو عدد مساوی باشند (مثلاً 5، 5، 3) برنامه‌ات چه می‌گوید؟
#      آیا جوابش درست است؟ تست کن.
#
#   ۲. کدام راه خواناتر است: `and` یا `if` های تودرتو؟ چرا؟
#
#   ۳. اگر کاربر جای عدد حرف بنویسد (مثلاً "abc") چه می‌شود؟
#      اسم آن خطا را حالا سه بار دیده‌ای.
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. اگر هر سه عدد مساوی بودند، پیام جداگانه بده.
#   ۲. کوچک‌ترین عدد را هم چاپ کن.
#   ۳. هر سه عدد را به‌ترتیب از بزرگ به کوچک چاپ کن.

# کد خودت را از این‌جا بنویس
a = float(input("First number:"))
b = float(input("Second number:"))
c = float(input("Third number:"))

if a >= b and a >= c:
    print(f"{a} is the largest")
elif b >= a and b >= c:
    print(f"{b} is the largest")
else:
    print(f"{c} is the largest")

