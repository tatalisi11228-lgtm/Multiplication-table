# تمرین ۰۷ — جدول ضرب
#
# صورت تمرین:
#   یک عدد از کاربر بگیر و جدول ضرب آن را از ۱ تا ۱۰ چاپ کن.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter a number: 7
#   7 x 1 = 7
#   7 x 2 = 14
#   7 x 3 = 21
#   7 x 4 = 28
#   7 x 5 = 35
#   7 x 6 = 42
#   7 x 7 = 49
#   7 x 8 = 56
#   7 x 9 = 63
#   7 x 10 = 70
#
# ---------------------------------------------------------------
# خوش آمدی به مرحلهٔ ۳: حلقه‌ها
# ---------------------------------------------------------------
#
#   تا حالا هر خط کدت **یک بار** اجرا می‌شد. حالا می‌خواهیم یک کار را
#   ۱۰ بار تکرار کنیم — بدون اینکه ۱۰ خط بنویسیم.
#
#   ابزار جدید: حلقهٔ for  به همراه  range()
#
#       for i in range(1, 11):
#           print(i)
#
#   این می‌گوید: «i را از ۱ تا ۱۰ بگذار و برای هر کدام، کارِ داخل حلقه
#   را انجام بده.»
#
#   سه چیز را از این تکه یادت بماند:
#
#   ۱. متغیر حلقه (اینجا i): هر دور، مقدارش عوض می‌شود. اسمش هر چه
#      باشد مهم نیست (i، n، عدد ...) — ولی کوتاه و روشن بهتر است.
#
#   ۲. بدنهٔ حلقه: خط‌های زیر for باید **۴ فاصله جلوتر** باشند — دقیقاً
#      مثل بدنهٔ if. پایتون از همین فاصله می‌فهمد چه چیزی داخل حلقه است.
#
#   ۳. range(1, 11)  عدد ۱ را می‌دهد ولی ... ۱۱ را **نمی‌دهد**!
#      یعنی ۱ تا ۱۰. (سؤال ۱ همین را می‌پرسد.)
#
#   برای جدول ضرب، هر دور باید یک خط چاپ کنی که هم عدد ورودی در آن
#   باشد، هم شمارهٔ دور (i) و هم حاصل‌ضربشان.
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. چرا range(1, 11) نوشتیم و نه range(1, 10)؟ اگر آن دومی را بنویسی،
#      خروجی‌ات چه فرقی می‌کند؟ (این «یکی کم و یکی زیاد» یکی از
#      معروف‌ترین اشتباهات برنامه‌نویسی دنیاست.)
#
#   ۲. اگر فقط range(5) بنویسی، چه اتفاقی می‌افتد؟ چند دور تکرار می‌شود
#      و i چه مقدارهایی می‌گیرد؟ حدس بزن، بعد امتحان کن.
#
#   ۳. اگر خط چاپ را **بدون فاصله** بنویسی (نه‌چسبیده به حلقه)، چه
#      می‌شود؟ چند خط چاپ می‌شود؟ چرا؟ (این هم یک باگ خاموش است — مثل
#      آن شاخهٔ جاافتاده در تمرین ۰۴.)
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. به‌جای ۱ تا ۱۰، از کاربر بپرس «تا کجا؟» — یعنی خودش انتهای
#      جدول را تعیین کند.
#   ۲. جدول‌های ضرب ۱ تا ۵ را پشت سر هم چاپ کن (راهنما: حلقه داخل حلقه).

# کد خودت را از این‌جا بنویس
number = int(input("Enter a number:"))

for i in range(1, 11):
    print(f"{number} x {i} = {number * i}")
