# تمرین ۰۹ — بازی حدس عدد
#
# صورت تمرین:
#   برنامه یک عدد تصادفی بین ۱ تا ۱۰۰ انتخاب می‌کند. کاربر حدس می‌زند و
#   برنامه می‌گوید «بالاتر» یا «پایین‌تر»، تا وقتی درست حدس بزند. آخرش
#   بگو در چند حدس موفق شد.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   I'm thinking of a number between 1 and 100.
#   Your guess: 50
#   Too low!
#   Your guess: 75
#   Too high!
#   Your guess: 63
#   Correct! You got it in 3 guesses.
#
# ---------------------------------------------------------------
# ابزار جدید ۱: حلقهٔ while — «تا وقتی که»
# ---------------------------------------------------------------
#
#   تا حالا for داشتیم: «این کار را n بار انجام بده» — تعداد از قبل
#   معلوم بود. حالا while: «تا وقتی این شرط درست است، تکرار کن» — و
#   تعداد از قبل معلوم نیست! نمی‌دانی کاربر چند حدس لازم دارد.
#
#       while شرط:
#           کاری که تا وقتی شرط درست است تکرار شود
#
#   پایتون **قبل از هر دور** شرط را چک می‌کند:
#     درست بود    → بدنه را اجرا کن، بعد برگرد و دوباره چک کن
#     نادرست بود  → حلقه تمام است؛ برو خط بعدِ حلقه
#
#   ⚠️ نکتهٔ مرگبار: چیزی داخل حلقه باید شرط را به سمت «نادرست» ببرد،
#   وگرنه حلقه هیچوقت تمام نمی‌شود (حلقهٔ بی‌پایان). اینجا هر حدس،
#   guess را عوض می‌کند تا بالاخره با عدد مخفی برابر شود.
#
#   تفاوت با for در یک جمله:
#     for   → «برای هر چیزی در این مجموعه» (تعداد معلوم)
#     while → «تا وقتی این شرط برقرار است» (تعداد نامعلوم)
#
# ---------------------------------------------------------------
# ابزار جدید ۲: عدد تصادفی
# ---------------------------------------------------------------
#
#       import random                       ← ابزار random را بگیر
#       secret = random.randint(1, 100)
#
#   import باید بالای فایل باشد، قبل از هر استفاده‌ای.
#
#   random.randint(1, 100) → یک عدد صحیح تصادفی، و **هر دو سر شامل** است:
#   ۱ و ۱۰۰ هم می‌توانند بیایند. (توجه: این با range فرق دارد که کران
#   بالایش شامل نیست! randint(1, 100) واقعاً یعنی بین ۱ و ۱۰۰.)
#
# ---------------------------------------------------------------
# ابزار جدید ۳: شمارنده
# ---------------------------------------------------------------
#
#   همان الگوی جمع‌کننده، ولی این بار به‌جای جمع، یکی‌یکی می‌شماریم:
#
#       tries = 0                  ← قبل از حلقه
#       ...
#       tries = tries + 1          ← هر دور، یکی اضافه
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. شرط حلقه را چه بگذاریم؟ (راهنما: «تا وقتی حدس با عدد مخفی برابر
#      نیست».) و یک مشکل: شرط **قبل** از دور اول چک می‌شود — آن وقت
#      مقدار guess چیست؟ دو راه‌حل:
#         الف) guess را قبل از حلقه یک مقدار اولیه بده (مثلاً 0)
#         ب)  از while True: استفاده کن و با break بیرون بزن
#      هر دو درست‌اند؛ هر کدام را راحت‌تری انتخاب کن.
#
#   ۲. اگر tries = 0 را داخل حلقه بگذاری چه می‌شود؟ (همان باگ خاموش ۰۸)
#
#   ۳. اگر کاربر جای عدد حرف بزند چه می‌شود؟ اسم آن خطا را می‌دانی.
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. حدس‌ها را به ۷ تا محدود کن؛ اگر تمام شد، عدد مخفی را بگو.
#   ۲. اگر ورودی بیرون از ۱ تا ۱۰۰ بود، آن را نشمار و پیام بده.
#   ۳. بعد از پایان بپرس «دوباره بازی کنیم؟» — (راهنما: یک while بیرونی)

# کد خودت را از این‌جا بنویس
print("I'm thinking of a number between 1 and 100.")

import random

secret = random.randint(1, 100)
tries = 0
while True:
    guess = int(input("Your guess: "))

    tries = tries + 1

    if guess == secret:
        break
    elif guess < secret:
        print("Too low!")
    else:
        print("Too high!")

print(f"Correct! You got it in {tries} guesses. 😀👌")


