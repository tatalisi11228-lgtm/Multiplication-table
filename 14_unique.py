# تمرین ۱۴ — حذف تکراری‌ها از لیست
#
# صورت تمرین:
#   چند عدد از کاربر بگیر، تکراری‌ها را حذف کن، و لیست تمیز را چاپ کن —
#   **با نگه داشتن ترتیب اولین ظهور** هر عدد.
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter numbers: 3 1 3 7 1 7 7
#   [3, 1, 7]
#
#   Enter numbers: 5 5 5 5
#   [5]
#
# ---------------------------------------------------------------
# قدم ۰: گرفتن عددها در یک لیست
# ---------------------------------------------------------------
#
#   کاربر همهٔ عددها را در یک خط، با فاصله، تایپ می‌کند:
#   «3 1 3 7 1 7 7». با split() می‌شود لیستی از **رشته‌ها**:
#   ['3', '1', '3', '7', '1', '7', '7']
#
#   برای اینکه عدد باشند، هر عضو را تبدیل کن (الگوی ۱۳):
#
#       raw = input("Enter numbers: ").split()
#       numbers = []
#       for item in raw:
#           numbers.append(int(item))
#
#   بعد از این، numbers یک لیست واقعی از اعداد است.
#
# ---------------------------------------------------------------
# ابزار جدید: in و not in
# ---------------------------------------------------------------
#
#   می‌پرسد: «آیا این چیز داخل این لیست هست؟»
#
#       3 in [1, 2, 3]        →  True
#       5 in [1, 2, 3]        →  False
#       5 not in [1, 2, 3]    →  True
#
#   (روی رشته هم کار می‌کند:  'a' in 'cat'  →  True)
#
# ---------------------------------------------------------------
# ایدهٔ الگوریتم: لیست جدید
# ---------------------------------------------------------------
#
#   یک لیست **خالی جدید** بردار و اعضای لیست اصلی را یکی‌یکی نگاه کن؛
#   هر عضو را فقط اگر **قبلاً اضافه نشده** اضافه کن:
#
#       unique = []
#       for n in numbers:
#           if n not in unique:
#               unique.append(n)
#
#   چرا لیست جدید؟ چون حذف از «وسط» یک لیست موجود دردسر دارد؛ ساختن
#   یک لیست تازه هم ساده‌تر است، هم ترتیب را خودت کنترل می‌کنی.
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. اگر جای `if n not in unique:` بنویسی `if n in unique:` چه
#      می‌شود؟ چه چیزی چاپ می‌شود؟ چرا؟
#
#   ۲. برای ورودی «3 1 3 7 1 7 7» حلقه چند بار اجرا می‌شود و چند عدد
#      به unique اضافه می‌شود؟ قبل از اجرا حدس بزن.
#
#   ۳. `set()` همین کار را یک خطی می‌کند: `list(set(numbers))`. چرا
#      این تمرین می‌گوید با حلقه بنویس؟ (راهنما: ترتیب را امتحان کن.)
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   ۱. بعد از چاپ، بگو چند تکراری حذف شد. (راهنما: طول اصلی منهای طول تمیز)
#   ۲. لیست را طوری چاپ کن که عددها با فاصله بیایند، نه با براکت:
#      3 1 7
#      (راهنما: حلقه + `print(n, end=" ")`)
#   ۳. کار را **بدون** ساختن لیست جدید انجام بده (حذف از خودِ لیست).
#      (این یکی سخت‌تر است و به remove() نیاز دارد.)

# کد خودت را از این‌جا بنویس
while True:
    raw = input("> Enter your numbers(press enter to skip) : ").split()

    if len(raw) == 0:
        print("process stopped")
        break
    numbers = []
    for item in raw:
        if item.isdigit():
            numbers.append(int(item))
        else:
            print(f"skipping: {item}")
    unique = []
    for n in numbers:
        if n not in unique:
            unique.append(n)

    print("Unique:", unique)
    removed = len(numbers) - len(unique)
    if removed == 1:
        print(f"Removed: {removed} duplicate")
    elif removed == 0:
        print("No duplicate")
    else:
        print(f"Removed: {removed} duplicates")
