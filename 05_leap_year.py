# تمرین ۰۵ — سال کبیسه
#
# صورت تمرین:
#   از کاربر یک سال بگیر و بگو کبیسه است یا نه.
#
#   قانون کبیسه در تقویم میلادی:
#     ۱. اگر سال بر ۴ بخش‌پذیر باشد           → کبیسه است
#     ۲. مگر اینکه بر ۱۰۰ بخش‌پذیر باشد       → کبیسه نیست
#     ۳. مگر اینکه بر ۴۰۰ بخش‌پذیر باشد       → کبیسه است
#
# نمونهٔ اجرا (خروجی تو باید شبیه این باشد):
#   Enter a year: 2024
#   2024 is a leap year
#
#   Enter a year: 1900
#   1900 is not a leap year
#
# ---------------------------------------------------------------
# ابزار جدید: باقی‌ماندهٔ تقسیم  %   و   and / or
# ---------------------------------------------------------------
#
#   %  باقی‌ماندهٔ تقسیم را می‌دهد، نه خارج‌قسمت:
#       2024 % 4   →  0      یعنی ۲۰۲۴ بر ۴ بخش‌پذیر است
#       2025 % 4   →  1
#
#   پس «بخش‌پذیر بر ۴» به زبان پایتون می‌شود:    year % 4 == 0
#   و «بخش‌پذیر نیست» می‌شود:                    year % 4 != 0
#
#   and  →  هر دو شرط باید درست باشند
#   or   →  کافی است یکی درست باشد
#
#   یک تکهٔ نمونه (این خودش جواب نیست، فقط شکل کار را نشان می‌دهد):
#       if year % 4 == 0 and year % 100 != 0:
#           print("...")
#
#   سال را با int() بگیر — سال عدد صحیح است، نه اعشاری.
#   (یادت باشد input() همیشه رشته می‌دهد.)
#
# ---------------------------------------------------------------
# سه سؤال برای فکر کردن
# ---------------------------------------------------------------
#
#   ۱. اگر فقط بنویسی year % 4 == 0، برای کدام سال‌ها جواب غلط می‌دهی؟
#      (راهنما: ۱۹۰۰ و ۲۰۰۰ را امتحان کن — یکی از این دو کبیسه است و
#       یکی نه، ولی هر دو بر ۴ بخش‌پذیرند.)
#
#   ۲. می‌توانی بدون and بنویسی — با if های تودرتو؟ کدام خواناتر است؟
#
#   ۳. اگر کاربر جای عدد حرف بنویسد (مثلاً "abc") چه می‌شود؟
#      اسم آن خطا را قبلاً دیده‌ای.
#
# ---------------------------------------------------------------
# چالش اضافه (اختیاری)
# ---------------------------------------------------------------
#   برای سال کبیسه ۳۶۶ روز و برای بقیه ۳۶۵ روز چاپ کن.
#   همچنین اگر سال کمتر از ۱ بود، پیام خطا بده.

# کد خودت را از این‌جا بنویس



year = int(input("Enter a year:"))

if year % 400 == 0:
    print(f"{year} is a leap year")
elif year % 100 == 0:
    print(f"{year} is not a leap year")
elif year % 4 == 0:
    print(f"{year} is a leap year")
elif year < 1:
    print("enter a year more that 1")
else:
    print(f"{year} is not a leap year")
